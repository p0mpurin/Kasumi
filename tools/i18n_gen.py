#!/usr/bin/env python3
"""Build source/i18n_table.c from the translation files.

i18n/*.tsv hold one line per text: the English exactly as it appears in
i18n/strings.txt (C escapes kept), then a tab-separated translation per
language (ja fr de es it pt, same escapes; empty = not translated). Lines starting with # are comments. Checks that each
translation keeps the English text's printf conversions in order, that no
two English texts share a hash, and reports what is missing per language.

    python tools/i18n_gen.py
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
LANGS = ["en", "ja", "fr", "de", "es", "it", "pt"]   # order of Lang in i18n.h
CONVERSION = re.compile(r"%(?:%|[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|z|j|t|L)?[diouxXeEfgGcsp])")


def unescape(s):
    """The bytes the C compiler makes of a literal's content."""
    out = bytearray()
    i = 0
    raw = s.encode("utf-8")
    while i < len(raw):
        c = raw[i]
        if c == 0x5C and i + 1 < len(raw):
            n = chr(raw[i + 1])
            simple = {"n": 10, "t": 9, "r": 13, '"': 34, "\\": 92, "'": 39, "0": 0}
            if n == "x":
                m = re.match(rb"[0-9a-fA-F]{1,2}", raw[i + 2:])
                out.append(int(m.group(0), 16))
                i += 2 + len(m.group(0))
                continue
            if n in simple:
                out.append(simple[n])
                i += 2
                continue
        out.append(c)
        i += 1
    return bytes(out)


def fnv1a(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def conversions(s):
    return [c for c in CONVERSION.findall(s) if c != "%%"]


def c_literal(s):
    """A translation as a C literal: keep its escapes, escape bare quotes."""
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s):
            out.append(s[i:i + 2])
            i += 2
            continue
        if ch == '"':
            out.append('\\"')
        elif ch == "?" and i + 1 < len(s) and s[i + 1] == "?":
            out.append("?\\")                       # no trigraphs
        else:
            out.append(ch)
        i += 1
    return '"' + "".join(out) + '"'


def main():
    strings = [l.rstrip("\n") for l in open(os.path.join(ROOT, "i18n", "strings.txt"), encoding="utf-8") if l.strip()]
    known = set(strings)
    hashes = {}
    for s in strings:
        h = fnv1a(unescape(s))
        if h in hashes and hashes[h] != s:
            sys.exit(f"hash collision: {s!r} / {hashes[h]!r}")
        hashes[h] = s
    errors = 0
    out = ["/* Generated by tools/i18n_gen.py from the i18n translation files. Do not edit. */",
           "#include <stdint.h>", "#include <stddef.h>", "", '#include "i18n.h"', "",
           "typedef struct {", "    uint32_t hash;", "    const char *text;", "} I18nEntry;", ""]
    # Every i18n/*.tsv: English, then one column per language in LANGS order
    # after English (ja fr de es it pt). An empty column is "not translated".
    per_lang = {code: {} for code in LANGS[1:]}
    tsvs = sorted(f for f in os.listdir(os.path.join(ROOT, "i18n")) if f.endswith(".tsv"))
    for fname in tsvs:
        for n, line in enumerate(open(os.path.join(ROOT, "i18n", fname), encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            cols = line.split("\t")
            en = cols[0]
            if en not in known:
                print(f"{fname}:{n}: not in strings.txt: {en[:60]!r}")
                continue
            if len(cols) != len(LANGS):
                print(f"{fname}:{n}: {len(cols)} columns, want {len(LANGS)}: {en[:50]!r}")
                errors += 1
                continue
            for code, text in zip(LANGS[1:], cols[1:]):
                if not text:
                    continue
                if conversions(en) != conversions(text):
                    print(f"{fname}:{n} [{code}]: placeholders differ: {conversions(en)} vs {conversions(text)}")
                    errors += 1
                    continue
                per_lang[code][fnv1a(unescape(en))] = text
    names = [None]
    for code in LANGS[1:]:
        entries = per_lang[code]
        print(f"{code}: {len(entries)} translated, {len(known) - len(entries)} missing")
        if not entries:
            names.append(None)
            continue
        name = f"I18N_{code.upper()}"
        names.append(name)
        out.append(f"static const I18nEntry {name}[] = {{")
        for h in sorted(entries):
            out.append(f"    {{ 0x{h:08x}u, {c_literal(entries[h])} }},")
        out.append("};")
        out.append("")
    out.append("const I18nEntry *const I18N_TABLES[LANG_COUNT] = {")
    out.extend(f"    {n if n else 'NULL'}," for n in names)
    out.append("};")
    out.append("const unsigned I18N_COUNTS[LANG_COUNT] = {")
    out.extend(f"    {f'sizeof({n}) / sizeof({n}[0])' if n else '0'}," for n in names)
    out.append("};")
    with open(os.path.join(ROOT, "source", "i18n_table.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    if errors:
        sys.exit(f"{errors} error(s)")


if __name__ == "__main__":
    main()
